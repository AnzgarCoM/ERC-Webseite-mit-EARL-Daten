create policy "Own profile or admin read" on public.profiles for select using (id=auth.uid() or public.is_earl_admin());
create policy "Public teams read" on public.teams for select using (true);
create policy "Public accepted drivers read" on public.drivers for select using (status='accepted' or public.is_earl_admin());
create policy "Public races read" on public.races for select using (true);
create policy "Public rules read" on public.rules for select using (published=true or public.is_earl_admin());
create policy "Public content read" on public.site_content for select using (true);
create policy "Public registration submit" on public.registrations for insert with check (status='pending');
create policy "Public event signup" on public.event_signups for insert with check (status='pending' and (signup_type='qualifying' or qualifying_confirmed=true));

create policy "Admins manage profiles" on public.profiles for all using (public.is_earl_admin()) with check (public.is_earl_admin());
create policy "Admins manage teams" on public.teams for all using (public.is_earl_admin()) with check (public.is_earl_admin());
create policy "Admins manage drivers" on public.drivers for all using (public.is_earl_admin()) with check (public.is_earl_admin());
create policy "Admins manage races" on public.races for all using (public.is_earl_admin()) with check (public.is_earl_admin());
create policy "Admins manage registrations" on public.registrations for all using (public.is_earl_admin()) with check (public.is_earl_admin());
create policy "Admins manage event signups" on public.event_signups for all using (public.is_earl_admin()) with check (public.is_earl_admin());
create policy "Admins manage rules" on public.rules for all using (public.is_earl_admin()) with check (public.is_earl_admin());
create policy "Admins manage content" on public.site_content for all using (public.is_earl_admin()) with check (public.is_earl_admin());


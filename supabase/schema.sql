create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text unique,
  is_admin boolean not null default false,
  created_at timestamptz not null default now()
);
create table if not exists public.teams (
  id text primary key,
  name text not null,
  short_code text not null,
  primary_color text not null default '#ff284c',
  secondary_color text not null default '#ffffff',
  team_principal text not null default 'Noch offen',
  is_available boolean not null default true,
  team_chief_card_url text,
  driver_card_url text,
  updated_at timestamptz not null default now()
);
create table if not exists public.drivers (
  id bigint generated by default as identity primary key,
  display_name text not null,
  discord_name text,
  nationality text,
  race_number integer check (race_number between 1 and 999),
  team_id text references public.teams(id) on delete set null,
  role text not null default 'Stammfahrer',
  card_image_url text,
  championship_points integer not null default 0,
  penalty_points integer not null default 0,
  wins integer not null default 0,
  podiums integer not null default 0,
  status text not null default 'accepted' check (status in ('pending','accepted','rejected')),
  updated_at timestamptz not null default now()
);
create table if not exists public.races (
  id bigint generated by default as identity primary key,
  round integer not null,
  name text not null,
  circuit text,
  qualifying_date date,
  qualifying_time time,
  race_date date,
  race_time time,
  status text not null default 'Geplant',
  qualifying_open boolean not null default true,
  race_open boolean not null default true,
  updated_at timestamptz not null default now()
);
create table if not exists public.registrations (
  id bigint generated by default as identity primary key,
  display_name text not null,
  discord_name text not null,
  nationality text,
  race_number integer check (race_number between 1 and 999),
  platform text,
  requested_team_id text references public.teams(id) on delete set null,
  notes text,
  status text not null default 'pending' check (status in ('pending','accepted','rejected')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.event_signups (
  id bigint generated by default as identity primary key,
  driver_name text not null,
  discord_name text not null,
  race_id bigint not null references public.races(id) on delete cascade,
  signup_type text not null check (signup_type in ('race','qualifying')),
  qualifying_confirmed boolean not null default false,
  notes text,
  status text not null default 'pending',
  created_at timestamptz not null default now(),
  constraint race_requires_qualifying_confirmation check (signup_type <> 'race' or qualifying_confirmed = true)
);
create table if not exists public.rules (
  id bigint generated by default as identity primary key,
  chapter text not null,
  title text not null,
  content text not null,
  sort_order integer not null default 0,
  published boolean not null default true,
  updated_at timestamptz not null default now()
);
create table if not exists public.site_content (
  id bigint generated by default as identity primary key,
  page_key text not null,
  content_key text not null,
  value text not null,
  updated_at timestamptz not null default now(),
  unique(page_key, content_key)
);

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public
as $$ begin
  insert into public.profiles (id,email) values (new.id,new.email)
  on conflict (id) do update set email=excluded.email;
  return new;
end; $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert or update of email on auth.users
for each row execute procedure public.handle_new_user();

create or replace function public.is_earl_admin()
returns boolean language sql stable security definer set search_path = public
as $$ select coalesce((select is_admin from public.profiles where id=auth.uid()),false); $$;

